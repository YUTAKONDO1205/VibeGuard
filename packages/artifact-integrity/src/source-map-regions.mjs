// Attributing an offset in a shipped artefact to the source it came from.
//
// ── WHY THIS FILE EXISTS ────────────────────────────────────────────────────
//
// `cross-examine.mjs` decides which artefact a claim is ABOUT — jurisdiction:
// the artefact's `sourcesContent` carries the text the rule matched — and then
// asks one question of it: does the witness token occur in the shipped code?
//
// Jurisdiction killed the CROSS-chunk false PRESENT. A vendor bundle that
// happens to spell `isAdmin` is no longer consulted about somebody else's
// claim. It does nothing at all about the WITHIN-chunk one, and that one is
// not hypothetical: a chunk holds hundreds of modules, a witness is four to
// seven characters of ordinary JavaScript, and one unrelated module in the
// same chunk carrying that token makes a defence the minifier genuinely
// deleted read PRESENT. Jurisdiction narrows the search to the right FILE; it
// says nothing about which of that file's hundreds of modules the hit is in.
//
// ── THE PRINCIPLE THIS IMPLEMENTS ───────────────────────────────────────────
//
// Absence over the whole chunk is sound as absence over the part. If the token
// is nowhere in the file, it is nowhere in the claim's own code either — so
// LOST, and the REINTRODUCED that can follow it, needs nothing from this
// module and is left exactly as it was. Only PRESENCE requires attribution.
//
// So this module answers one question: does THIS offset in the generated text
// belong to THAT source? Three answers are possible and the third is the one
// that matters — yes, no, and cannot tell. `cross-examine.mjs` turns the third
// into NOT_OBSERVED. It must never turn into either polarity: a "no" that is
// really a "cannot tell" reports a surviving defence as removed, and a "yes"
// that is really a "cannot tell" is the false PRESENT this file exists to
// remove.
//
// ── WHY THE SOURCE MAP AND NOT SOMETHING ELSE ───────────────────────────────
//
// Three alternatives were considered and rejected. Counting occurrences and
// requiring exactly one is not attribution, it is a coincidence detector, and
// it fails on the ordinary case of a token used twice in the claimant's own
// file. Re-minifying the claim's source and looking for the result reproduces
// the build, needs the build's own configuration, and answers a different
// question. Requiring the witness to sit near other tokens from the same
// source is a similarity score with a threshold nobody can justify. The map is
// the build's own statement of where each generated byte came from; it is
// already on disk beside the artefact, already read by `bundle.mjs`, and costs
// no dependency.
//
// ── AND WHY THE DECODER IS HAND-WRITTEN ─────────────────────────────────────
//
// `packages/artifact-integrity` declares zero dependencies and
// `test/boundary.test.mjs` asserts it. A VLQ reader for Source Map revision 3
// is sixty lines. This file is deliberately NOT listed in the package's
// `exports`: `bundle.mjs` and `cross-examine.mjs` reach it by relative path,
// so nothing about the packaging invariants changes.

/** Base64 alphabet of Source Map revision 3, as a lookup table. */
const B64 = new Int32Array(128).fill(-1);
for (let i = 0; i < 64; i += 1) {
  B64['ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'.charCodeAt(i)] = i;
}

/**
 * The widest run of generated text one mapping segment may cover and still be
 * treated as saying where that text came from.
 *
 * ── WHAT THIS DEFENDS AGAINST ───────────────────────────────────────────────
 *
 * A map is free to be as coarse as its producer likes. The degenerate shape is
 * one segment per generated LINE, and a minified bundle's code-bearing lines
 * are tens of thousands of characters holding dozens of modules. Attributing
 * an offset inside a span like that to the source the span names would be the
 * same false PRESENT this module was written to remove, arriving through the
 * mechanism meant to remove it. So a span wider than this cap attributes
 * nothing, and an offset inside one is unattributable.
 *
 * ── MEASURED, 2026-08-24, esbuild 0.21.5, `--minify --sourcemap` ────────────
 *
 * Five real bundles built from this repository. Widths are of RAW segment
 * spans — segment start to the next segment start on the same generated line,
 * or to end of line — in generated characters:
 *
 *   bundle           sources  code bytes  segments  median  p95  p99.9  max
 *   the CLI test's         1         205        34       3   14     36    36
 *   chrome background      1       4,708       880       3   15    132   132
 *   chrome side panel     35     159,910    21,088       3   16    266   825
 *   vscode extension      41     169,975    22,827       3   16    264   825
 *   the CLI itself        79     375,052    60,739       3   14    252   825
 *
 * The distribution is nowhere near this cap: the median span is three
 * characters and the 99.9th percentile is under 270. Above 512 there is
 * exactly ONE span in the side panel and in the vscode extension and TWO in
 * the CLI — 0.40 to 0.52% of mapped bytes — and every one of them is a single
 * long regular-expression literal. No identifier-bearing code is dropped by
 * this cap in any bundle measured.
 *
 * The other end is just as far away. In those same bundles the longest
 * generated line is 52,360, 52,360 and 53,136 characters, so the line-granular
 * map this cap exists to reject produces spans two orders of magnitude above
 * it. 512 sits in a gap that nothing measured comes close to, which is why it
 * is not stated to any more precision than that.
 */
export const SPAN_ATTRIBUTION_CAP = 512;

/**
 * Segments this decoder will read from one artefact before giving up.
 *
 * Measured above at 0.16 segments per generated byte (60,739 over 375,052).
 * `MAX_ARTEFACT_BYTES` allows a 64 MB artefact, which at that density is about
 * ten million segments; two million is roughly a 12 MB minified bundle,
 * comfortably past anything a browser is served. Past the cap the decode is
 * INVALID, not truncated — a half-read mapping table would attribute the first
 * half of a file correctly and silently attribute nothing in the second, which
 * is a partial view wearing the clothes of a complete one.
 */
export const MAX_MAPPING_SEGMENTS = 2_000_000;

/**
 * Decode a source map's `mappings` into generated-text regions.
 *
 * `code` must already be newline-normalised, and the caller is
 * `bundle.mjs#normaliseText`. That is safe for column arithmetic, and it is
 * worth saying why rather than trusting it: map columns are counted from the
 * start of their own generated line, and the `\r` normalisation removes is the
 * LAST character of a CRLF line, so no column within any line moves. Absolute
 * offsets do move, which is exactly why the line-start table below is built
 * from the normalised text rather than from the bytes on disk.
 *
 * Returns `{ regions, coarse, segments }` on success and `{ regions: null,
 * why }` otherwise. Every validity failure invalidates the WHOLE decode for
 * the artefact rather than dropping the offending segment: a decoder that
 * repairs a malformed table as it goes is guessing, and its output looks
 * exactly like a good one to everything downstream.
 */
export function decodeSourceRegions(code, map) {
  if (!map || typeof map !== 'object') {
    return { regions: null, why: 'there is no source map object to decode' };
  }
  // An index map. `sections` holds whole nested maps at generated offsets, and
  // a decoder that ignored the key would read either a `mappings` that is not
  // there or the sections' own, offset by an amount it never applied, and
  // produce regions that are confidently wrong. Refused, not mis-decoded.
  if (map.sections !== undefined) {
    return {
      regions: null,
      why: 'the source map is an index map (it has a "sections" key), which this decoder does not read',
    };
  }
  if (typeof map.mappings !== 'string') {
    return { regions: null, why: 'the source map has no "mappings" string' };
  }
  if (!Array.isArray(map.sources)) {
    return { regions: null, why: 'the source map has no "sources" array, so a segment\'s source index names nothing' };
  }
  const sourceCount = map.sources.length;
  if (!sourceCount) {
    return { regions: null, why: 'the source map lists no sources' };
  }
  // Line counts of the original files, used to reject an origLine that cannot
  // exist. Known only where the map republished the text; where it did not,
  // the range check is skipped rather than faked.
  const origLines = [];
  for (let i = 0; i < sourceCount; i += 1) {
    const c = Array.isArray(map.sourcesContent) ? map.sourcesContent[i] : null;
    origLines.push(typeof c === 'string' ? c.split('\n').length : -1);
  }

  const codeLines = code.split('\n');
  const lineStart = new Array(codeLines.length);
  for (let i = 0, off = 0; i < codeLines.length; i += 1) {
    lineStart[i] = off;
    off += codeLines[i].length + 1;
  }

  /** Raw spans in generated order. A `null` marks one the cap dropped. */
  const raw = [];
  const coarse = [];
  let segments = 0;
  let src = 0;
  let origLine = 0;
  let origCol = 0;
  let nameIdx = 0;

  const groups = map.mappings.split(';');
  for (let gl = 0; gl < groups.length; gl += 1) {
    const group = groups[gl];
    if (!group) continue;
    if (gl >= codeLines.length) {
      return {
        regions: null,
        why: `the mappings describe generated line ${gl + 1} and the artefact has ${codeLines.length}`,
      };
    }
    const lineLen = codeLines[gl].length;
    const base = lineStart[gl];
    const onLine = [];
    let genCol = 0;
    for (const seg of group.split(',')) {
      if (!seg) continue;
      segments += 1;
      if (segments > MAX_MAPPING_SEGMENTS) {
        return { regions: null, why: `the mappings hold more than ${MAX_MAPPING_SEGMENTS} segments` };
      }
      // ── VLQ ──────────────────────────────────────────────────────────────
      const fields = [];
      let value = 0;
      let shift = 0;
      let cont = 0;
      for (let i = 0; i < seg.length; i += 1) {
        const ch = seg.charCodeAt(i);
        const digit = ch < 128 ? B64[ch] : -1;
        if (digit < 0) {
          return { regions: null, why: `segment ${segments} of the mappings is not base64 VLQ` };
        }
        cont = digit & 32;
        // `2 ** shift` and not `<< shift`: the shift operators coerce to int32,
        // so a six-digit value would wrap to a negative number that passes
        // every range check below.
        value += (digit & 31) * 2 ** shift;
        shift += 5;
        if (shift > 40) {
          return { regions: null, why: `segment ${segments} of the mappings encodes an out-of-range value` };
        }
        if (!cont) {
          fields.push(value % 2 ? -Math.floor(value / 2) : Math.floor(value / 2));
          value = 0;
          shift = 0;
        }
      }
      if (cont) {
        return { regions: null, why: `segment ${segments} of the mappings ends mid-value` };
      }
      // ── VALIDITY ─────────────────────────────────────────────────────────
      //
      // This is the runtime control of this feature, and unlike the negative
      // control it replaces, every branch below is reachable: each is a shape
      // a real producer can emit or a mis-decode can reach. A violation sends
      // the artefact to the unattributable branch — never to PRESENT.
      if (fields.length !== 1 && fields.length !== 4 && fields.length !== 5) {
        return {
          regions: null,
          why: `segment ${segments} of the mappings has ${fields.length} fields, and revision 3 allows 1, 4 or 5`,
        };
      }
      genCol += fields[0];
      if (genCol < 0) {
        return { regions: null, why: `segment ${segments} of the mappings is at generated column ${genCol}` };
      }
      if (fields.length === 1) {
        // A generated-only segment: this offset maps to no source. Recorded
        // because it ENDS whatever span preceded it on this line.
        onLine.push({ col: genCol, source: -1 });
        continue;
      }
      src += fields[1];
      origLine += fields[2];
      origCol += fields[3];
      if (fields.length === 5) nameIdx += fields[4];
      if (src < 0 || src >= sourceCount) {
        return { regions: null, why: `segment ${segments} of the mappings names source ${src} of ${sourceCount}` };
      }
      if (origLine < 0 || origCol < 0) {
        return {
          regions: null,
          why: `segment ${segments} of the mappings points at original line ${origLine + 1}, column ${origCol}`,
        };
      }
      if (origLines[src] >= 0 && origLine >= origLines[src]) {
        return {
          regions: null,
          why: `segment ${segments} of the mappings points at line ${origLine + 1} of a source that has ${origLines[src]}`,
        };
      }
      if (nameIdx < 0) {
        return { regions: null, why: `segment ${segments} of the mappings names index ${nameIdx} of the names table` };
      }
      onLine.push({ col: genCol, source: src });
    }
    for (let i = 0; i < onLine.length; i += 1) {
      if (onLine[i].source < 0) continue;
      const start = base + onLine[i].col;
      const end = base + (i + 1 < onLine.length ? onLine[i + 1].col : lineLen);
      if (end <= start) continue;
      if (end - start > SPAN_ATTRIBUTION_CAP) {
        // Kept only so the caller can say WHY an offset inside it could not be
        // attributed. It attributes nothing.
        coarse.push({ start, end });
        raw.push(null);
        continue;
      }
      raw.push({ start, end, source: onLine[i].source });
    }
  }

  // ── MERGE ────────────────────────────────────────────────────────────────
  //
  // Adjacent spans of the same source become one region, which is what keeps a
  // lookup cheap on a bundle with sixty thousand segments. A DROPPED span
  // breaks the chain — merging across one would quietly put the over-cap text
  // back inside an attributed region and undo the cap.
  const regions = [];
  let prev = null;
  for (const span of raw) {
    if (!span) {
      prev = null;
      continue;
    }
    // A gap of exactly one is the `\n` between two generated lines.
    if (prev && prev.source === span.source && span.start - prev.end <= 1) {
      prev.end = span.end;
      continue;
    }
    prev = { start: span.start, end: span.end, source: span.source };
    regions.push(prev);
  }
  coarse.sort((a, b) => a.start - b.start);
  return { regions, coarse, segments };
}

/**
 * The source index whose region contains `offset`, or -1.
 *
 * Binary search over regions that are sorted and non-overlapping by
 * construction: segments arrive in generated order and each span ends where
 * the next one begins.
 */
export function regionSourceAt(regions, offset) {
  let lo = 0;
  let hi = regions.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const r = regions[mid];
    if (offset < r.start) hi = mid - 1;
    else if (offset >= r.end) lo = mid + 1;
    else return r.source;
  }
  return -1;
}

/** Width of the over-cap span containing `offset`, or 0 if there is none. */
export function coarseWidthAt(coarse, offset) {
  let lo = 0;
  let hi = coarse.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const c = coarse[mid];
    if (offset < c.start) hi = mid - 1;
    else if (offset >= c.end) lo = mid + 1;
    else return c.end - c.start;
  }
  return 0;
}

/**
 * Which of the map's sources carry this claim's source text.
 *
 * NOT a path match. `cross-examine.mjs` already decides which ARTEFACT a claim
 * belongs to by asking whether its `sourcesContent` contains the probe; this
 * asks the identical question of each entry separately, so the source index
 * rests on the same predicate as the jurisdiction it refines rather than on a
 * second, weaker one. Bundlers rewrite `sources` paths at least four ways
 * (`webpack:///./src/x.ts`, absolute, relative, `../../`), which is why the
 * existing basename comparison in `cross-examine.mjs` is only ever allowed to
 * be a tie-break.
 *
 * Several entries can match — code splitting duplicates a module across entry
 * points, and a re-exporting barrel republishes it. The caller unions them.
 */
export function sourceIndexesCarrying(contents, probe) {
  const out = [];
  for (let i = 0; i < contents.length; i += 1) {
    const c = contents[i];
    if (typeof c === 'string' && c.includes(probe)) out.push(i);
  }
  return out;
}

// ── DELIBERATELY NOT IMPLEMENTED ────────────────────────────────────────────
//
// "Promote to LOST when the witness is confidently attributed to a DIFFERENT
// source." It is tempting: if every occurrence of `isAdmin` in this chunk sits
// inside node_modules' regions, the claim's own copy really is gone, and LOST
// would be both true and more useful than NOT_OBSERVED.
//
// It is not implemented because the confidence it needs is not available at
// the granularity measured above. `regionSourceAt` returning some other source
// is evidence of absence only if the claim's own regions were mapped
// COMPLETELY, and a map is free to leave generated text unmapped — between
// 0.2% and 16.1% of the generated bytes in the five bundles measured for the
// cap carry no mapping at all. So v1 falls to NOT_OBSERVED. That costs a line
// of output; the alternative costs an accusation that a defence was removed
// when it was not.
