// VG-SMELL-010 — join the human labels back onto the measured population, and
// refuse to compute a precision figure until the labels are actually confirmed.
//
// WHY THIS SCRIPT IS MOSTLY REFUSALS
//
// `smell010-eval.mjs` deliberately has no field to put a precision number in,
// because a precision number requires a human to read the implicated handlers
// and decide. This script is where that number becomes computable — which makes
// it exactly the place where the number can be fabricated. A harness that will
// happily print "precision 100% (n=5)" from five rows nobody read is worse than
// no harness at all: it launders an assumption into a measurement, and the
// laundering is invisible in the output.
//
// So the gate is mechanical rather than cultural:
//
//   1. Every finding in the population must have exactly one label row. A
//      missing label is an unconfirmed verdict, not an absent one.
//   2. Every label row must carry `humanConfirmed: true`. ONE false anywhere
//      and no rate is printed — no partial rate over the confirmed subset
//      either, because a rate over the rows that happened to be easy is a
//      biased rate with an honest-looking denominator.
//   3. Every label row must quote evidence, and every quote must be FOUND in
//      the file it claims, at the line it claims. This is the one part of "did
//      you actually read it" a script can check, so it checks it.
//   4. The rubric version on the labels must exist in the rubric document. A
//      label set citing a rubric nobody can read is unreviewable.
//
// What the script CANNOT check, stated because a checklist that hides its gaps
// is worse than one that admits them: whether `humanConfirmed: true` is true.
// A person can set it without reading anything, and no amount of tooling here
// would notice. `labeledBy` is the mitigation — it names who to ask — and the
// output prints it next to the number so the provenance travels with the claim.
//
// Run from the repo root:
//   node scripts/smell010-precision.mjs
//   node scripts/smell010-precision.mjs --init   # write a labelling template
//
// Reads  paper_data/smell010_eval.json      (the population; `label` all null)
//        paper_data/smell010_labels.json    (the verdicts; hand-written)
// Writes nothing unless --init.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const REPO_ROOT = process.cwd();
const argValue = (name, fallback) => {
  const i = process.argv.indexOf(name);
  if (i === -1) return fallback;
  const v = process.argv[i + 1];
  return v === undefined || v.startsWith('--') ? fallback : v;
};
const argFlag = (name) => process.argv.includes(name);

const EVAL_PATH = argValue('--eval', join(REPO_ROOT, 'paper_data', 'smell010_eval.json'));
const LABELS_PATH = argValue('--labels', join(REPO_ROOT, 'paper_data', 'smell010_labels.json'));
const RUBRIC_PATH = argValue('--rubric', join(REPO_ROOT, 'docs', 'smell010-labeling-rubric.md'));
const TEMPLATE_PATH = argValue(
  '--template-out',
  join(REPO_ROOT, 'paper_data', 'smell010_labels.template.json'),
);
const CORPUS_DIR = {
  baseline: join(REPO_ROOT, 'paper_data', 'corpus1k'),
  vibe: join(REPO_ROOT, 'paper_data', 'corpus1k_vibe'),
};

const VERDICTS = new Set(['TP', 'FP', 'uncertain']);
/** A rationale shorter than this is a verdict with no reasoning attached. */
const MIN_RATIONALE = 40;

const out = (s) => process.stdout.write(`${s}\n`);
const fail = (s) => process.stderr.write(`${s}\n`);

/**
 * Recompute the join key from the population row.
 *
 * `smell010-eval.mjs` writes `findingKey` onto every finding, and this function
 * is a SECOND implementation of the same recipe rather than a reader of the
 * first. When both are present they are compared, and a disagreement is a hard
 * error: two scripts silently disagreeing about which finding a label belongs to
 * is how a verdict ends up attached to the wrong repository, which is the one
 * failure mode that would be invisible in every number downstream.
 */
function findingKeyOf(finding) {
  const first = (finding.sites ?? [])[0];
  return `${finding.corpus}/${finding.repo}#VG-SMELL-010#${first ? first.filePath : '?'}:${
    first ? first.startLine : 0
  }#n${(finding.sites ?? []).length}`;
}

// ── Load the population ─────────────────────────────────────────────────────

if (!existsSync(EVAL_PATH)) {
  fail(`No population file at ${EVAL_PATH}. Run: node scripts/smell010-eval.mjs --limit 0`);
  process.exit(2);
}
const evalJson = JSON.parse(readFileSync(EVAL_PATH, 'utf8'));
const population = (evalJson.findings ?? []).filter((f) => f.ruleId === 'VG-SMELL-010');
const errorRows = (evalJson.findings ?? []).filter((f) => f.error);

// A population row carrying a non-null `label` means someone wrote a verdict
// into the measurement file. That file is regenerated by every run, so the
// verdict is both destined for deletion and in the one place the design says
// verdicts may not live.
const strayLabels = population.filter((f) => f.label !== null && f.label !== undefined);

for (const f of population) {
  const recomputed = findingKeyOf(f);
  if (f.findingKey && f.findingKey !== recomputed) {
    fail('KEY DRIFT: the population file and this script disagree about a finding key.');
    fail(`  stored:     ${f.findingKey}`);
    fail(`  recomputed: ${recomputed}`);
    fail('Labels joined under one recipe and read under another would attach verdicts to');
    fail('the wrong findings. Fix the recipe in both places before going further.');
    process.exit(2);
  }
  f.findingKey = f.findingKey || recomputed;
}

// An empty population is not "precision undefined, carry on" — it almost always
// means the file in place is a smoke run (`--limit 2`) rather than the full pass,
// and reporting anything at all off it would be reporting on two repositories
// while looking like a corpus-wide result.
if (population.length === 0) {
  out('');
  out('# VG-SMELL-010 — precision: NOT COMPUTED');
  out('');
  out(`\`${EVAL_PATH}\` contains **no VG-SMELL-010 findings**.`);
  const analysed = Object.values(evalJson.summary ?? {})
    .map((s) => `${s.corpus} ${s.reposAnalysed}/${s.reposAvailable}`)
    .join(', ');
  if (analysed) out(`Its summary covers: ${analysed}.`);
  out('');
  out('If those denominators are a sample rather than the full corpus, this file is a');
  out('smoke run and there is nothing to label yet. Produce the population first:');
  out('  node scripts/smell010-eval.mjs --limit 0');
  process.exit(1);
}

// ── --init: emit a template, never overwrite real labels ────────────────────

if (argFlag('--init')) {
  if (existsSync(TEMPLATE_PATH)) {
    fail(`${TEMPLATE_PATH} already exists; refusing to overwrite it.`);
    process.exit(2);
  }
  const rubricVersion = readRubricVersion() ?? 's010-label-v1';
  writeFileSync(
    TEMPLATE_PATH,
    JSON.stringify(
      {
        rubricVersion,
        rubric: 'docs/smell010-labeling-rubric.md',
        _howToUse:
          'Fill in verdict / rationale / evidenceQuotes / labeledBy for every row, set ' +
          'humanConfirmed to true ONLY for rows a human actually read, then save as ' +
          'paper_data/smell010_labels.json and run scripts/smell010-precision.mjs. ' +
          'verdict is null here on purpose: an unfilled row must not look like a verdict.',
        labels: population.map((f) => ({
          corpus: f.corpus,
          repo: f.repo,
          findingKey: f.findingKey,
          verdict: null,
          rationale: '',
          evidenceQuotes: [],
          labeledBy: '',
          humanConfirmed: false,
          _sites: f.sites,
        })),
      },
      null,
      2,
    ),
  );
  out(`Wrote ${TEMPLATE_PATH} with ${population.length} row(s) to label.`);
  out('Rename to paper_data/smell010_labels.json once filled in.');
  process.exit(0);
}

// ── Load the labels ─────────────────────────────────────────────────────────

function readRubricVersion() {
  if (!existsSync(RUBRIC_PATH)) return null;
  const m = /rubricVersion:\s*([\w.\-]+)/.exec(readFileSync(RUBRIC_PATH, 'utf8'));
  return m ? m[1] : null;
}

if (!existsSync(LABELS_PATH)) {
  out('');
  out(`# VG-SMELL-010 — precision: NOT COMPUTED`);
  out('');
  out(`Population: ${population.length} finding(s) in \`${EVAL_PATH}\`.`);
  out(`Labels:     none — \`${LABELS_PATH}\` does not exist.`);
  out('');
  out(`**未確認が ${population.length} 件あるので精度率は出せない。**`);
  out('');
  out('Start with:  node scripts/smell010-precision.mjs --init');
  out(`Then label against \`${RUBRIC_PATH}\` and re-run.`);
  process.exit(1);
}

let labelsJson;
try {
  labelsJson = JSON.parse(readFileSync(LABELS_PATH, 'utf8'));
} catch (err) {
  fail(`${LABELS_PATH} is not valid JSON: ${err && err.message}`);
  process.exit(2);
}

// ── Validate ────────────────────────────────────────────────────────────────

const problems = [];
const push = (kind, detail) => problems.push({ kind, detail });

const rubricVersion = readRubricVersion();
if (!labelsJson.rubricVersion) {
  push('rubric', 'labels file has no `rubricVersion`');
} else if (rubricVersion === null) {
  push('rubric', `rubric document ${RUBRIC_PATH} not found, so the cited rubric cannot be read`);
} else if (labelsJson.rubricVersion !== rubricVersion) {
  push(
    'rubric',
    `labels cite rubricVersion "${labelsJson.rubricVersion}" but ${RUBRIC_PATH} declares ` +
      `"${rubricVersion}". A verdict is only interpretable against the criteria it was made ` +
      `under; re-label under the current rubric or restore the cited one.`,
  );
}

const labels = Array.isArray(labelsJson.labels) ? labelsJson.labels : [];
const byKey = new Map();
for (const l of labels) {
  const key = l.findingKey;
  if (!key) {
    push('shape', `a label row has no findingKey (${l.corpus}/${l.repo})`);
    continue;
  }
  if (byKey.has(key)) push('duplicate', `two label rows for ${key}`);
  byKey.set(key, l);
}

const populationKeys = new Set(population.map((f) => f.findingKey));
for (const key of byKey.keys()) {
  if (!populationKeys.has(key)) {
    push(
      'orphan',
      `label for ${key} matches no finding in the population — the measurement was re-run ` +
        `and this finding moved or vanished, so the verdict is stale`,
    );
  }
}

/**
 * Verify a quoted line against the file it was quoted from.
 *
 * The single check here that touches ground truth. Everything else validates the
 * labels file against itself; this one asks the corpus whether the text a
 * labeller says they read is where they say it is. A quote that is not there
 * means the row was written without opening the file — which is precisely the
 * failure this whole apparatus exists to prevent, and it is undetectable by any
 * amount of reading the labels file.
 *
 * Line numbers are 1-based, matching `sites[].startLine`. A ±2 line window is
 * allowed because a labeller copying a multi-line condition may cite the line
 * the statement starts on; a wrong FILE is never tolerated.
 */
function verifyQuote(corpus, repo, quote) {
  const dir = CORPUS_DIR[corpus];
  if (!dir) return { ok: false, why: `unknown corpus "${corpus}"` };
  if (!existsSync(dir)) return { ok: false, why: `corpus directory missing: ${dir}` };
  const file = join(dir, repo, quote.file ?? '');
  if (!existsSync(file)) return { ok: false, why: `file not found: ${repo}/${quote.file}` };
  let lines;
  try {
    lines = readFileSync(file, 'utf8').split(/\r?\n/);
  } catch (err) {
    return { ok: false, why: `unreadable: ${err && err.message}` };
  }
  const needle = String(quote.text ?? '').trim();
  if (needle === '') return { ok: false, why: 'empty quote text' };
  const at = Number(quote.line);
  if (!Number.isFinite(at) || at < 1) return { ok: false, why: `bad line number ${quote.line}` };
  for (let i = Math.max(1, at - 2); i <= Math.min(lines.length, at + 2); i += 1) {
    if (lines[i - 1] !== undefined && lines[i - 1].includes(needle)) return { ok: true };
  }
  return {
    ok: false,
    why: `quote not found at ${repo}/${quote.file}:${at} (±2 lines): ${JSON.stringify(needle.slice(0, 60))}`,
  };
}

let unconfirmed = 0;
let unlabelled = 0;
const counts = { TP: 0, FP: 0, uncertain: 0 };
const byLabeller = new Map();

for (const f of population) {
  const l = byKey.get(f.findingKey);
  if (!l) {
    unlabelled += 1;
    push('unlabelled', `no label row for ${f.findingKey}`);
    continue;
  }
  if (!VERDICTS.has(l.verdict)) {
    push('verdict', `${f.findingKey}: verdict is ${JSON.stringify(l.verdict)}, expected TP/FP/uncertain`);
  } else {
    counts[l.verdict] += 1;
  }
  if (typeof l.rationale !== 'string' || l.rationale.trim().length < MIN_RATIONALE) {
    push(
      'rationale',
      `${f.findingKey}: rationale is missing or shorter than ${MIN_RATIONALE} characters — the ` +
        `rubric requires which sites were discarded and what remained`,
    );
  }
  if (typeof l.labeledBy !== 'string' || l.labeledBy.trim() === '') {
    push('labeledBy', `${f.findingKey}: labeledBy is empty — who made this call must be recorded`);
  } else {
    byLabeller.set(l.labeledBy, (byLabeller.get(l.labeledBy) ?? 0) + 1);
  }
  if (l.humanConfirmed !== true) {
    unconfirmed += 1;
    push('unconfirmed', `${f.findingKey}: humanConfirmed is not true`);
  }
  const quotes = Array.isArray(l.evidenceQuotes) ? l.evidenceQuotes : [];
  if (quotes.length === 0) {
    push('evidence', `${f.findingKey}: no evidenceQuotes — the rubric requires at least one`);
  }
  for (const q of quotes) {
    const v = verifyQuote(l.corpus ?? f.corpus, l.repo ?? f.repo, q);
    if (!v.ok) push('evidence', `${f.findingKey}: ${v.why}`);
  }
}

for (const f of strayLabels) {
  push(
    'stray-label',
    `${f.findingKey}: the population file carries a non-null \`label\`. Verdicts belong in ` +
      `${LABELS_PATH}; this one will be destroyed by the next measurement run`,
  );
}

// ── Report ──────────────────────────────────────────────────────────────────

out('');
out('# VG-SMELL-010 — precision');
out('');
out(`- population: **${population.length}** finding(s) from \`${EVAL_PATH}\``);
out(`  (generated ${evalJson.generatedAt ?? 'unknown'}${errorRows.length > 0 ? `; ${errorRows.length} repositories failed to analyse and are not part of it` : ''})`);
out(`- labels:     **${labels.length}** row(s) from \`${LABELS_PATH}\``);
out(`- rubric:     ${labelsJson.rubricVersion ?? '(none)'} — \`${RUBRIC_PATH}\``);
out('');

if (problems.length > 0) {
  const grouped = new Map();
  for (const p of problems) {
    if (!grouped.has(p.kind)) grouped.set(p.kind, []);
    grouped.get(p.kind).push(p.detail);
  }
  out('## 精度率は出せない');
  out('');
  if (unconfirmed > 0 || unlabelled > 0) {
    out(`**未確認が ${unconfirmed + unlabelled} 件あるので精度率は出せない。**`);
    out(`（humanConfirmed でない ${unconfirmed} 件 ＋ ラベル行が無い ${unlabelled} 件）`);
  } else {
    out('**ラベルの検証に失敗したので精度率は出せない。**');
  }
  out('');
  for (const [kind, details] of grouped) {
    out(`### ${kind} (${details.length})`);
    for (const d of details.slice(0, 25)) out(`- ${d}`);
    if (details.length > 25) out(`- … and ${details.length - 25} more`);
    out('');
  }
  out('No rate is printed over the confirmed subset either: a precision computed on the');
  out('rows that happened to be easy is a biased number wearing an honest denominator.');
  process.exit(1);
}

// Everything checked out. Print the numbers, and print what they rest on.
const decided = counts.TP + counts.FP;
const total = counts.TP + counts.FP + counts.uncertain;
const pct = (n, d) => (d > 0 ? `${((n / d) * 100).toFixed(1)}%` : 'n/a');

out('## Verdicts');
out('');
out(`| TP | FP | uncertain | total |`);
out('|---|---|---|---|');
out(`| ${counts.TP} | ${counts.FP} | ${counts.uncertain} | ${total} |`);
out('');
out('## Precision');
out('');
out(`- excluding uncertain: **${pct(counts.TP, decided)}** (${counts.TP}/${decided})`);
out(
  `- bounds including uncertain: **${pct(counts.TP, total)} – ${pct(counts.TP + counts.uncertain, total)}** ` +
    `(uncertain all-FP … all-TP, n=${total})`,
);
if (counts.uncertain > 0) {
  out('');
  out(`⚠ ${counts.uncertain} finding(s) are uncertain. Quote the RANGE, not the point estimate:`);
  out('  a point estimate that silently drops the cases nobody could decide is the same');
  out('  error as dropping the repositories that failed to scan.');
}
if (total < 10) {
  out('');
  out(`⚠ n=${total}. This is a proportion over single digits; its confidence interval spans`);
  out('  most of the unit interval. Report the counts (x of y), not the percentage alone.');
}
out('');
out('## Provenance');
out('');
for (const [who, n] of byLabeller) out(`- ${n} row(s) labelled by: **${who}**`);
out('');
out('Every row asserts `humanConfirmed: true`. This script verified that each cited');
out('evidence quote exists in the file and line it cites; it cannot verify that a human');
out('read it. The `labeledBy` names above are the record of who to ask.');
