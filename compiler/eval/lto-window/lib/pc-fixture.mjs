/**
 * The positive control for the which-wipe reading: a family whose SUBJECT wipe
 * cannot legally be removed.
 *
 * WHY. tools/which-wipe-survived.mjs has, to date, only ever answered
 * `subject-store-already-gone`. That is the interesting answer, and it is also
 * exactly the answer a BROKEN pipe gives: a cut that deleted nothing, a build
 * that was not rebuilt, a reader pointed at an empty body -- each of them makes
 * "deleting the subject's wipe changed nothing" come out true. The lane's own
 * rule for every other reading it takes is that an instrument which can only
 * produce one word is not measuring. This family is that rule applied to this
 * tool: a case where the tool is REQUIRED to say `subject-store-still-there`,
 * and where saying `already-gone` is a failure of the tool rather than a finding
 * about the compiler.
 *
 * HOW IT DIFFERS FROM THE MEASURED FAMILY, AND IN WHAT. One line of one file.
 * io.c, wipe.c and main.c are COPIED from the lane's own fixture rather than
 * re-emitted here, for the same reason make-lto-fixtures.sh copies them between
 * its two families: nothing may drift between the family being checked and the
 * family doing the checking. use.c is written here, and the difference is the
 * ORDER of two calls in the subject:
 *
 *   the lane's subject   derive(key); use(key); secure_wipe(key);
 *                        -- the wipe is the last use of a dead stack buffer, so
 *                           the link may delete it, and does.
 *
 *   this subject         derive(key); secure_wipe(key); use(key);
 *                        -- the wiped bytes are then read by a function in a
 *                           unit that is never compiled -flto. The zeroes escape
 *                           the merged module, so no level may drop the store
 *                           and deleting the line from the source MUST move the
 *                           fill.
 *
 * THIS IS NOT A MEASUREMENT OF THE LANE. It is not a fourth family, it is not
 * evidence about wipes, and it is deliberately not generated by
 * tools/make-lto-fixtures.sh: the run-lto-window.mjs driver enumerates the
 * families that script writes, and a check's scaffolding appearing in a results
 * table would be worse than the hole it closes. It is written into the check's
 * own work directory, in the lab, and read by nothing else.
 *
 * `always_inline` rather than the measured family's bare absorption: the reading
 * is taken in one absorbed body, and whether the ordinary inliner absorbs these
 * two callers is a decision of the optimiser -- which is the thing under
 * observation everywhere else in this lane. A positive control may not depend on
 * it. Pinning the shape is how this family stays a test of the TOOL.
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** The unit the cut edits. Carries one line of each wipe, matching WIPE_LINES. */
export const PC_USE_C = `/* POSITIVE CONTROL for tools/check-which-wipe-plumbing.mjs.
 *
 * Not a measurement. Both wipes here are read afterwards through io.c, which is
 * never compiled -flto, so neither of them may be removed at any level -- and
 * the tool is therefore required to report that the subject's store is STILL
 * THERE. A tool that answers "already gone" here is broken in the direction that
 * produces this lane's published table.
 *
 * always_inline: the reading is taken in one absorbed body, and a control may
 * not depend on the optimiser choosing to absorb. See lib/pc-fixture.mjs. */

#include <string.h>

/* io.c -- never compiled -flto. */
void derive(unsigned char *out, unsigned long n);
void use(const unsigned char *p, unsigned long n);

/* wipe.c -- compiled -flto. */
void secure_wipe(void *p, unsigned long n);

/* SUBJECT. The wipe is NOT the last use of the buffer: the zeroed bytes are
 * handed to an opaque unit afterwards, so the store is live and no level may
 * delete it. Same helper, same buffer name, same line as the measured family --
 * only the order of the last two statements differs. */
__attribute__((always_inline))
void handle(void) {
    unsigned char key[32];
    derive(key, sizeof key);
    secure_wipe(key, sizeof key);
    use(key, sizeof key);
}

/* CONTROL, unchanged from the measured family: wiped, then read. */
__attribute__((always_inline))
void wipe_kept(void) {
    unsigned char keep[32];
    derive(keep, sizeof keep);
    memset(keep, 0, sizeof keep);
    use(keep, sizeof keep);
}
`;

/**
 * What this family must read, if the plumbing works. Two 32-byte buffers, both
 * of them un-removable, both absorbed into `main`: the as-written body carries
 * the sum, and each cut takes exactly one wipe's worth away.
 */
export const PC_EXPECTED = Object.freeze({
  caller: 'main',
  helper: 'secure_wipe',
  subjectBytes: 32,
  controlBytes: 64, // both wipes are in the one body; PRESENT is the pair of them
  reading: 'SUBJECT_PRESENT',
});

/** Copy the three unedited units from `fromFixture`, write use.c here. */
export function writePositiveControlFixture(fromFixture, destDir) {
  mkdirSync(destDir, { recursive: true });
  for (const f of ['io.c', 'wipe.c', 'main.c']) copyFileSync(join(fromFixture, f), join(destDir, f));
  writeFileSync(join(destDir, 'use.c'), PC_USE_C, 'utf8');
  return destDir;
}
